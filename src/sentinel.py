
"""ELO Sentinel: safe workspace activity monitoring."""

import json
import threading
from datetime import datetime
from pathlib import Path

from watchdog.events import FileSystemEventHandler
from watchdog.observers import Observer


PROJECT_DIR = Path(__file__).resolve().parent.parent
WATCH_DIR = PROJECT_DIR / "sentinel_watch"
LOG_FILE = PROJECT_DIR / "memory" / "sentinel_events.jsonl"


class SentinelHandler(FileSystemEventHandler):
    """Record filesystem event metadata without reading file contents."""

    def on_any_event(self, event):
        if event.is_directory:
            return

        # Ignore events generated by non-file operations.
        if event.event_type not in {
            "created", "modified", "deleted", "moved"
        }:
            return

        source_path = str(event.src_path)

        # Keep the monitor scoped to the dedicated watch directory.
        try:
            Path(source_path).resolve().relative_to(
                WATCH_DIR.resolve()
            )
        except (ValueError, OSError):
            return

        record = {
            "time": datetime.now().astimezone().isoformat(
                timespec="seconds"
            ),
            "event": event.event_type,
            "path": source_path,
        }

        if event.event_type == "moved":
            record["destination"] = str(event.dest_path)

        try:
            LOG_FILE.parent.mkdir(parents=True, exist_ok=True)
            with LOG_FILE.open("a", encoding="utf-8") as file:
                file.write(json.dumps(record, ensure_ascii=False) + "\n")
        except OSError as error:
            print(f"[Sentinel] Could not write event log: {error}")

        print(
            f"[Sentinel] {record['event'].upper()}: "
            f"{record['path']}"
        )


class ELOSentinel:
    """Start and stop the workspace monitor safely."""

    def __init__(self):
        self.observer = None
        self.lock = threading.Lock()

    def start(self):
        with self.lock:
            if self.observer is not None and self.observer.is_alive():
                return "ELO Sentinel is already running."

            WATCH_DIR.mkdir(parents=True, exist_ok=True)

            handler = SentinelHandler()
            observer = Observer()
            observer.schedule(
                handler,
                str(WATCH_DIR),
                recursive=True,
            )
            observer.start()
            self.observer = observer

        return (
            "ELO Sentinel started.\n"
            f"Watching: {WATCH_DIR}\n"
            f"Event log: {LOG_FILE}"
        )

    def stop(self):
        with self.lock:
            observer = self.observer

            if observer is None or not observer.is_alive():
                self.observer = None
                return "ELO Sentinel is not running."

            observer.stop()

        observer.join(timeout=5)

        with self.lock:
            if observer.is_alive():
                return (
                    "Sentinel is still stopping. "
                    "Please wait and try again."
                )
            self.observer = None

        return "ELO Sentinel stopped."

    def status(self):
        with self.lock:
            running = (
                self.observer is not None
                and self.observer.is_alive()
            )

        return (
            "ELO Sentinel: "
            + ("RUNNING" if running else "STOPPED")
            + f"\nWatch folder: {WATCH_DIR}"
            + f"\nEvent log: {LOG_FILE}"
        )


sentinel = ELOSentinel()
